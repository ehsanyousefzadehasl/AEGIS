DEFAULT_OUTPUT_CSV = "evaluation/threshold_sensitivity/live_threshold_measurements.csv"


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Launch one real workload, wait for TTFK + 30s window, and log live threshold metrics."
    )
    p.add_argument("--task", required=True, help="Path to workload file (.rad or .yaml/.yml).")
    p.add_argument("--workdir", required=True, help="Working directory used by AEGIS launch command.")
    p.add_argument("--user", default="threshold-exp", help="User label for the synthetic Task object.")
    p.add_argument("--gpu-uuid", default=None, help="GPU UUID to use.")
    p.add_argument("--gpu-id", default=None, help="GPU index/id to use (e.g., 0).")
    p.add_argument("--estimator", default="None", help="Estimator name for load_job_spec().")
    p.add_argument("--window-seconds", type=float, default=30.0, help="Post-TTFK window length.")
    p.add_argument("--ttfk-timeout", type=float, default=300.0, help="Timeout waiting for first GPU sighting.")
    p.add_argument("--window-timeout", type=float, default=600.0, help="Timeout waiting for post-TTFK window completion.")
    p.add_argument("--poll-seconds", type=float, default=0.5, help="Polling interval for gpu_state.update().")
    p.add_argument("--event-path", default=None, help="Optional explicit JSONL event path.")
    p.add_argument("--output-csv", default=DEFAULT_OUTPUT_CSV, help="CSV path for measurement rows.")
    p.add_argument("--run-id", default=None, help="Optional run id; autogenerated if omitted.")
    return p.parse_args()


def resolve_gpu_selection(args: argparse.Namespace, uuid_to_id: dict[str, str]) -> tuple[str, str]:
    if args.gpu_uuid:
        gpu_uuid = str(args.gpu_uuid)
        if gpu_uuid not in uuid_to_id:
            raise ValueError(f"--gpu-uuid {gpu_uuid} not found. Known UUIDs: {sorted(uuid_to_id.keys())}")
        return gpu_uuid, str(uuid_to_id[gpu_uuid])

    if args.gpu_id is not None:
        gpu_id = str(args.gpu_id)
        for known_uuid, known_id in uuid_to_id.items():
            if str(known_id) == gpu_id:
                return known_uuid, gpu_id
        raise ValueError(f"--gpu-id {gpu_id} not found. Known ids: {sorted(set(uuid_to_id.values()))}")

    if not uuid_to_id:
        raise RuntimeError("No GPUs found via monitor.gpu_uuids().")

    gpu_uuid = next(iter(uuid_to_id.keys()))
    return gpu_uuid, str(uuid_to_id[gpu_uuid])


def start_monitor_thread(window_seconds: float) -> Thread:
    t = Thread(
        target=monitor.monitor_logger,
        args=(int(window_seconds),),
        daemon=True,
    )
    t.start()
    return t


def wait_for_ttfk(gpu_uuid: str, timeout_s: float, poll_s: float) -> tuple[float, int]:
    deadline = time.monotonic() + timeout_s

    while time.monotonic() < deadline:
        gpu_state.update()
        row = gpu_state.gpus_state.loc[gpu_uuid]

        pid_val = row["CPU_task_PID"]
        if pd.isna(pid_val):
            raise RuntimeError("Tracked PID disappeared before TTFK was observed.")

        seen_at = row["gpu_seen_at"]
        if not pd.isna(seen_at):
            return float(seen_at), int(pid_val)

        time.sleep(poll_s)

    raise TimeoutError(f"Timed out waiting for TTFK on GPU {gpu_uuid}.")


def wait_for_window(gpu_uuid: str, timeout_s: float, poll_s: float) -> tuple[float, int]:
    deadline = time.monotonic() + timeout_s

    while time.monotonic() < deadline:
        gpu_state.update()
        row = gpu_state.gpus_state.loc[gpu_uuid]

        pid_val = row["CPU_task_PID"]
        if pd.isna(pid_val):
            raise RuntimeError("Tracked PID disappeared before the post-TTFK window completed.")

        if gpu_state.window_ready(gpu_uuid):
            return time.monotonic(), int(pid_val)

        time.sleep(poll_s)

    raise TimeoutError(f"Timed out waiting for post-TTFK window completion on GPU {gpu_uuid}.")


def append_measurement_csv(path: str | Path, row: dict) -> None:
    out_path = Path(path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    df = pd.DataFrame([row])
    if out_path.exists():
        df.to_csv(out_path, mode="a", header=False, index=False)
    else:
        df.to_csv(out_path, index=False)


def main() -> int:
    args = parse_args()

    task_path = os.path.abspath(args.task)
    workdir = os.path.abspath(args.workdir)
    run_id = args.run_id or str(uuid.uuid4())

    if not os.path.exists(task_path):
        raise FileNotFoundError(f"Task file does not exist: {task_path}")
    if not os.path.isdir(workdir):
        raise NotADirectoryError(f"Workdir does not exist: {workdir}")

    task_obj = Task(user=args.user, dir=workdir, task=task_path)
    job_spec = load_job_spec(task_path, args.estimator)

    uuid_to_id = monitor.gpu_uuids()
    gpu_uuid, gpu_id = resolve_gpu_selection(args, uuid_to_id)

    gpu_state.init_gpu_state(uuid_to_id)

    monitor_thread = start_monitor_thread(args.window_seconds)

    now_str = dt.datetime.now().strftime("%Y-%m-%d_%H:%M:%S")
    event_path = args.event_path or os.path.join(
        workdir,
        f"events-threshold-{now_str}-{task_obj.task_id}.jsonl",
    )

    command = build_launch_command(
        workdir,
        gpu_id,
        job_spec.command_to_execute,
        now_str,
        task_obj,
        event_path,
        run_id,
    )

    launcher_pid = launch_and_get_pid(command)
    if launcher_pid is None:
        raise RuntimeError("Failed to capture launcher PID from build_launch_command().")

    gpu_state.launch_task(
        gpu_uuid,
        launcher_pid,
        task_id=str(task_obj.task_id),
        event_path=event_path,
        window_seconds=float(args.window_seconds),
    )

    append_jsonl_event(
        event_path=event_path,
        record={
            "event": "threshold_runner_launched",
            "timestamp": now_str,
            "task_id": str(task_obj.task_id),
            "task": task_path,
            "workdir": workdir,
            "gpu_uuid": gpu_uuid,
            "gpu_id": gpu_id,
            "launcher_pid": launcher_pid,
            "run_id": run_id,
        },
    )

    Thread(
        target=resolve_and_update_gpu_pid,
        args=(launcher_pid, [gpu_uuid]),
        daemon=True,
    ).start()

    t_launch = time.monotonic()
    ttfk_seen_at, tracked_pid_after_ttfk = wait_for_ttfk(
        gpu_uuid,
        timeout_s=float(args.ttfk_timeout),
        poll_s=float(args.poll_seconds),
    )
    t_window_ready, tracked_pid_after_window = wait_for_window(
        gpu_uuid,
        timeout_s=float(args.window_timeout),
        poll_s=float(args.poll_seconds),
    )

    analyzed = monitor.analyze_Gmetrics()
    if gpu_uuid not in analyzed.index:
        raise RuntimeError(f"GPU {gpu_uuid} not found in analyze_Gmetrics() output.")

    metrics_row = analyzed.loc[gpu_uuid].to_dict()
    state_row = gpu_state.gpus_state.loc[gpu_uuid].to_dict()

    wall_now = dt.datetime.now().isoformat()
    measurement = {
        "measured_at": wall_now,
        "run_id": run_id,
        "task_id": str(task_obj.task_id),
        "task_path": task_path,
        "workdir": workdir,
        "gpu_uuid": gpu_uuid,
        "gpu_id": gpu_id,
        "launcher_pid": int(launcher_pid),
        "tracked_pid_after_ttfk": int(tracked_pid_after_ttfk),
        "tracked_pid_after_window": int(tracked_pid_after_window),
        "ttfk_wait_seconds": float(ttfk_seen_at - t_launch),
        "window_seconds": float(args.window_seconds),
        "time_from_ttfk_to_measurement": float(t_window_ready - ttfk_seen_at),
        "event_path": event_path,
        "command_to_execute": job_spec.command_to_execute,
        "num_gpus_requested": int(job_spec.num_gpus_requested),
        "gpu_memory_requirement_mib": job_spec.gpu_memory_requirement_mib,
        "gpu_memory_estimate_mib": job_spec.gpu_memory_estimate_mib,
        "state_validity_after_window": state_row.get("validity"),
        "state_gpu_seen_at": state_row.get("gpu_seen_at"),
        **metrics_row,
    }

    append_measurement_csv(args.output_csv, measurement)

    append_jsonl_event(
        event_path=event_path,
        record={
            "event": "threshold_measurement_recorded",
            "timestamp": wall_now,
            "task_id": str(task_obj.task_id),
            "task": task_path,
            "gpu_uuid": gpu_uuid,
            "gpu_id": gpu_id,
            "output_csv": str(args.output_csv),
            "run_id": run_id,
            "smact_risk": measurement.get("smact_risk", measurement.get("smact")),
            "smocc_risk": measurement.get("smocc_risk", measurement.get("smocc")),
            "drama_risk": measurement.get("drama_risk", measurement.get("drama")),
        },
    )

    print("measurement recorded")
    print(f"task_id={task_obj.task_id}")
    print(f"gpu_uuid={gpu_uuid}")
    print(f"gpu_id={gpu_id}")
    print(f"launcher_pid={launcher_pid}")
    print(f"tracked_pid_after_window={tracked_pid_after_window}")
    print(f"output_csv={args.output_csv}")
    print(
        "risk_scores:",
        {
            "smact_risk": measurement.get("smact_risk", measurement.get("smact")),
            "smocc_risk": measurement.get("smocc_risk", measurement.get("smocc")),
            "drama_risk": measurement.get("drama_risk", measurement.get("drama")),
        },
    )

    # keep reference so lint/static tools do not complain about the daemon thread
    _ = monitor_thread
    return 0


if __name__ == "__main__":
    raise SystemExit(main())