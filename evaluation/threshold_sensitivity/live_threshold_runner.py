def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Launch one real workload, wait for TTFK + post-TTFK window, then wait for completion and log runtime."
    )
    p.add_argument("--task", required=True, help="Path to workload file (.rad or .yaml/.yml).")
    p.add_argument("--workdir", required=True, help="Working directory used by AEGIS launch command.")
    p.add_argument("--user", default="threshold-exp", help="User label for the synthetic Task object.")
    p.add_argument("--gpu-uuid", default=None, help="GPU UUID to use.")
    p.add_argument("--gpu-id", default=None, help="GPU index/id to use (e.g., 0).")
    p.add_argument("--estimator", default="None", help="Estimator name for load_job_spec().")
    p.add_argument("--window-seconds", type=float, default=30.0, help="Post-TTFK window length.")
    p.add_argument("--ttfk-timeout", type=float, default=300.0, help="Timeout waiting for first GPU sighting.")
    p.add_argument("--window-timeout", type=float, default=600.0, help="Timeout waiting for post-TTFK window completion.")
    p.add_argument("--finish-timeout", type=float, default=0.0, help="Timeout waiting for workload finish. 0 means no timeout.")
    p.add_argument("--poll-seconds", type=float, default=0.5, help="Polling interval.")
    p.add_argument("--event-path", default=None, help="Optional explicit JSONL event path.")
    p.add_argument("--output-csv", default=DEFAULT_OUTPUT_CSV, help="CSV path for measurement rows.")
    p.add_argument("--index-csv", default=DEFAULT_INDEX_CSV, help="CSV path for one row per attempted run.")
    p.add_argument("--run-id", default=None, help="Optional run id; autogenerated if omitted.")
    return p.parse_args()


def resolve_gpu_selection(args: argparse.Namespace, uuid_to_id: dict[str, str]) -> tuple[str, str]:
    if args.gpu_uuid:
        gpu_uuid = str(args.gpu_uuid)
        if gpu_uuid not in uuid_to_id:
            raise ValueError(f"--gpu-uuid {gpu_uuid} not found. Known UUIDs: {sorted(uuid_to_id.keys())}")
        return gpu_uuid, str(uuid_to_id[gpu_uuid])

    if args.gpu_id is not None:
        gpu_id = str(args.gpu_id)
        for known_uuid, known_id in uuid_to_id.items():
            if str(known_id) == gpu_id:
                return known_uuid, gpu_id
        raise ValueError(f"--gpu-id {gpu_id} not found. Known ids: {sorted(set(uuid_to_id.values()))}")

    if not uuid_to_id:
        raise RuntimeError("No GPUs found via monitor.gpu_uuids().")

    gpu_uuid = next(iter(uuid_to_id.keys()))
    return gpu_uuid, str(uuid_to_id[gpu_uuid])


def start_monitor_thread(window_seconds: float) -> Thread:
    t = Thread(
        target=monitor.monitor_logger,
        args=(int(window_seconds),),
        daemon=True,
    )
    t.start()
    return t


def wait_for_ttfk(gpu_uuid: str, timeout_s: float, poll_s: float) -> tuple[float, int]:
    deadline = time.monotonic() + timeout_s

    while time.monotonic() < deadline:
        gpu_state.update()
        row = gpu_state.gpus_state.loc[gpu_uuid]

        pid_val = row["CPU_task_PID"]
        if pd.isna(pid_val):
            raise RuntimeError("Tracked PID disappeared before TTFK was observed.")

        seen_at = row["gpu_seen_at"]
        if not pd.isna(seen_at):
            return float(seen_at), int(pid_val)

        time.sleep(poll_s)

    raise TimeoutError(f"Timed out waiting for TTFK on GPU {gpu_uuid}.")


def wait_for_window(gpu_uuid: str, timeout_s: float, poll_s: float) -> tuple[float, int]:
    deadline = time.monotonic() + timeout_s

    while time.monotonic() < deadline:
        gpu_state.update()
        row = gpu_state.gpus_state.loc[gpu_uuid]

        pid_val = row["CPU_task_PID"]
        if pd.isna(pid_val):
            raise RuntimeError("Tracked PID disappeared before the post-TTFK window completed.")

        if gpu_state.window_ready(gpu_uuid):
            return time.monotonic(), int(pid_val)

        time.sleep(poll_s)

    raise TimeoutError(f"Timed out waiting for post-TTFK window completion on GPU {gpu_uuid}.")


def wait_for_finish(tracked_pid: int, finish_timeout_s: float, poll_s: float) -> float:
    deadline = None if finish_timeout_s <= 0 else (time.monotonic() + finish_timeout_s)

    while True:
        if not monitor.pid_on_system(str(tracked_pid)):
            return time.monotonic()

        if deadline is not None and time.monotonic() >= deadline:
            raise TimeoutError(f"Timed out waiting for tracked PID {tracked_pid} to finish.")

        time.sleep(poll_s)


def read_terminal_event(event_path: str | Path, task_id: str, run_id: str, wait_s: float = 5.0) -> dict | None:
    deadline = time.monotonic() + wait_s
    path = Path(event_path)

    while time.monotonic() < deadline:
        if path.exists():
            last_match = None
            with path.open("r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    try:
                        record = json.loads(line)
                    except json.JSONDecodeError:
                        continue

                    if str(record.get("task_id")) != str(task_id):
                        continue
                    if str(record.get("run_id")) != str(run_id):
                        continue
                    if record.get("event") in {"completed", "failed"}:
                        last_match = record

            if last_match is not None:
                return last_match

        time.sleep(0.25)

    return None


def append_csv_row(path: str | Path, row: dict, columns: list[str] | None = None) -> None:
    out_path = Path(path)
    out_path.parent.mkdir(parents=True, exist_ok=True)

    if columns is not None:
        normalized = {column: row.get(column) for column in columns}
        extra_columns = sorted(set(row) - set(normalized))
        for column in extra_columns:
            normalized[column] = row[column]
        row = normalized

    df = pd.DataFrame([row])
    if out_path.exists():
        df.to_csv(out_path, mode="a", header=False, index=False)
    else:
        df.to_csv(out_path, index=False)


def append_measurement_csv(path: str | Path, row: dict) -> None:
    append_csv_row(path, row)


def append_run_index_csv(path: str | Path, row: dict) -> None:
    append_csv_row(path, row, columns=INDEX_COLUMNS)

def main() -> int:
    args = parse_args()

    task_path = os.path.abspath(args.task)
    workdir = os.path.abspath(args.workdir)
    run_id = args.run_id or str(uuid.uuid4())
    t_start = time.monotonic()

    task_obj: Task | None = None
    job_spec = None
    gpu_uuid = None
    gpu_id = None
    launcher_pid = None
    tracked_pid_after_ttfk = None
    tracked_pid_after_window = None
    t_launch = None
    ttfk_seen_at = None
    t_window_ready = None
    t_finish = None
    launch_wall = None
    terminal_event_name = None
    return_code = None
    terminal_failure_reason = None
    finish_status = "not_started"
    event_path = args.event_path
    out_log = None
    err_log = None
    time_log = None
    measurement_recorded = False
    stage = "initialization"
    monitor_thread = None

    index_row = {
        "recorded_at": dt.datetime.now().isoformat(),
        "run_id": run_id,
        "runner_status": "started",
        "workload_status": finish_status,
        "failure_stage": None,
        "failure_reason": None,
        "measurement_recorded": False,
        "task_id": None,
        "task_path": task_path,
        "workdir": workdir,
        "gpu_uuid": None,
        "gpu_id": None,
        "launcher_pid": None,
        "tracked_pid_after_ttfk": None,
        "tracked_pid_after_window": None,
        "launch_wall_time": None,
        "finished_wall_time": None,
        "ttfk_wait_seconds": None,
        "window_seconds": float(args.window_seconds),
        "time_from_ttfk_to_window_ready_seconds": None,
        "total_runtime_seconds": None,
        "time_from_window_ready_to_finish_seconds": None,
        "event_path": event_path,
        "out_log": None,
        "err_log": None,
        "time_log": None,
        "terminal_event": None,
        "return_code": None,
        "terminal_failure_reason": None,
        "output_csv": args.output_csv,
        "command_to_execute": None,
        "num_gpus_requested": None,
        "gpu_memory_requirement_mib": None,
        "gpu_memory_estimate_mib": None,
    }

    try:
        stage = "validate_inputs"
        if not os.path.exists(task_path):
            raise FileNotFoundError(f"Task file does not exist: {task_path}")
        if not os.path.isdir(workdir):
            raise NotADirectoryError(f"Workdir does not exist: {workdir}")

        stage = "load_job_spec"
        task_obj = Task(user=args.user, dir=workdir, task=task_path)
        job_spec = load_job_spec(task_path, args.estimator)
        index_row.update(
            {
                "task_id": str(task_obj.task_id),
                "command_to_execute": job_spec.command_to_execute,
                "num_gpus_requested": int(job_spec.num_gpus_requested),
                "gpu_memory_requirement_mib": job_spec.gpu_memory_requirement_mib,
                "gpu_memory_estimate_mib": job_spec.gpu_memory_estimate_mib,
            }
        )

        stage = "select_gpu"
        uuid_to_id = monitor.gpu_uuids()
        gpu_uuid, gpu_id = resolve_gpu_selection(args, uuid_to_id)
        index_row.update({"gpu_uuid": gpu_uuid, "gpu_id": gpu_id})

        stage = "init_monitoring"
        gpu_state.init_gpu_state(uuid_to_id)
        monitor_thread = start_monitor_thread(args.window_seconds)

        now_str = dt.datetime.now().strftime("%Y-%m-%d_%H:%M:%S")
        event_path = event_path or os.path.join(
            workdir,
            f"events-threshold-{now_str}-{task_obj.task_id}.jsonl",
        )

        out_log = os.path.join(workdir, f"out-{now_str}-{task_obj.task_id}.log")
        err_log = os.path.join(workdir, f"err-{now_str}-{task_obj.task_id}.log")
        time_log = os.path.join(workdir, f"time-{now_str}-{task_obj.task_id}.et")
        index_row.update(
            {
                "event_path": event_path,
                "out_log": out_log,
                "err_log": err_log,
                "time_log": time_log,
            }
        )

        command = build_launch_command(
            workdir,
            gpu_id,
            job_spec.command_to_execute,
            now_str,
            task_obj,
            event_path,
            run_id,
        )

        stage = "launch"
        t_launch = time.monotonic()
        launch_wall = dt.datetime.now().isoformat()
        index_row.update(
            {
                "runner_status": "launching",
                "launch_wall_time": launch_wall,
            }
        )

        launcher_pid = launch_and_get_pid(command)
        if launcher_pid is None:
            raise RuntimeError("Failed to capture launcher PID from build_launch_command().")
        index_row.update({"launcher_pid": int(launcher_pid), "runner_status": "launched"})

        gpu_state.launch_task(
            gpu_uuid,
            launcher_pid,
            task_id=str(task_obj.task_id),
            event_path=event_path,
            window_seconds=float(args.window_seconds),
        )

        append_jsonl_event(
            event_path=event_path,
            record={
                "event": "threshold_runner_launched",
                "timestamp": launch_wall,
                "task_id": str(task_obj.task_id),
                "task": task_path,
                "workdir": workdir,
                "gpu_uuid": gpu_uuid,
                "gpu_id": gpu_id,
                "launcher_pid": launcher_pid,
                "run_id": run_id,
            },
        )

        Thread(
            target=resolve_and_update_gpu_pid,
            args=(launcher_pid, [gpu_uuid]),
            daemon=True,
        ).start()

        stage = "wait_for_ttfk"
        ttfk_seen_at, tracked_pid_after_ttfk = wait_for_ttfk(
            gpu_uuid,
            timeout_s=float(args.ttfk_timeout),
            poll_s=float(args.poll_seconds),
        )
        index_row.update(
            {
                "runner_status": "ttfk_ready",
                "tracked_pid_after_ttfk": int(tracked_pid_after_ttfk),
                "ttfk_wait_seconds": float(ttfk_seen_at - t_launch),
            }
        )

        stage = "wait_for_window"
        t_window_ready, tracked_pid_after_window = wait_for_window(
            gpu_uuid,
            timeout_s=float(args.window_timeout),
            poll_s=float(args.poll_seconds),
        )
        index_row.update(
            {
                "runner_status": "window_ready",
                "tracked_pid_after_window": int(tracked_pid_after_window),
                "time_from_ttfk_to_window_ready_seconds": float(t_window_ready - ttfk_seen_at),
            }
        )

        stage = "analyze_metrics"
        analyzed = monitor.analyze_Gmetrics()
        if gpu_uuid not in analyzed.index:
            raise RuntimeError(f"GPU {gpu_uuid} not found in analyze_Gmetrics() output.")

        metrics_row = analyzed.loc[gpu_uuid].to_dict()
        state_row = gpu_state.gpus_state.loc[gpu_uuid].to_dict()

        stage = "wait_for_finish"
        t_finish = wait_for_finish(
            tracked_pid_after_window,
            finish_timeout_s=float(args.finish_timeout),
            poll_s=float(args.poll_seconds),
        )
        gpu_state.update()

        stage = "read_terminal_event"
        terminal_event = read_terminal_event(
            event_path=event_path,
            task_id=str(task_obj.task_id),
            run_id=run_id,
            wait_s=5.0,
        )

        finish_status = "unknown"

        if terminal_event is not None:
            terminal_event_name = terminal_event.get("event")
            return_code = terminal_event.get("return_code")
            terminal_failure_reason = terminal_event.get("failure_reason")

            if terminal_event_name == "completed":
                finish_status = "completed"
            elif terminal_event_name == "failed":
                finish_status = "failed"

        if return_code is not None:
            return_code = int(return_code)

        wall_now = dt.datetime.now().isoformat()
        measurement = {
            "measured_at": wall_now,
            "run_id": run_id,
            "task_id": str(task_obj.task_id),
            "task_path": task_path,
            "workdir": workdir,
            "gpu_uuid": gpu_uuid,
            "gpu_id": gpu_id,
            "launcher_pid": int(launcher_pid),
            "tracked_pid_after_ttfk": int(tracked_pid_after_ttfk),
            "tracked_pid_after_window": int(tracked_pid_after_window),
            "launch_wall_time": launch_wall,
            "ttfk_wait_seconds": float(ttfk_seen_at - t_launch),
            "window_seconds": float(args.window_seconds),
            "time_from_ttfk_to_window_ready_seconds": float(t_window_ready - ttfk_seen_at),
            "total_runtime_seconds": float(t_finish - t_launch),
            "time_from_window_ready_to_finish_seconds": float(t_finish - t_window_ready),
            "event_path": event_path,
            "out_log": out_log,
            "err_log": err_log,
            "time_log": time_log,
            "finish_status": finish_status,
            "terminal_event": terminal_event_name,
            "return_code": return_code,
            "terminal_failure_reason": terminal_failure_reason,
            "command_to_execute": job_spec.command_to_execute,
            "num_gpus_requested": int(job_spec.num_gpus_requested),
            "gpu_memory_requirement_mib": job_spec.gpu_memory_requirement_mib,
            "gpu_memory_estimate_mib": job_spec.gpu_memory_estimate_mib,
            "state_validity_at_measurement": state_row.get("validity"),
            "state_gpu_seen_at": state_row.get("gpu_seen_at"),
            **metrics_row,
        }

        stage = "write_measurement"
        append_measurement_csv(args.output_csv, measurement)
        measurement_recorded = True

        append_jsonl_event(
            event_path=event_path,
            record={
                "event": "threshold_measurement_recorded",
                "timestamp": wall_now,
                "task_id": str(task_obj.task_id),
                "task": task_path,
                "gpu_uuid": gpu_uuid,
                "gpu_id": gpu_id,
                "output_csv": str(args.output_csv),
                "run_id": run_id,
                "smact_risk": measurement.get("smact_risk", measurement.get("smact")),
                "smocc_risk": measurement.get("smocc_risk", measurement.get("smocc")),
                "drama_risk": measurement.get("drama_risk", measurement.get("drama")),
                "finish_status": finish_status,
                "return_code": return_code,
                "terminal_failure_reason": terminal_failure_reason,
                "total_runtime_seconds": measurement["total_runtime_seconds"],
            },
        )

        index_row.update(
            {
                "recorded_at": wall_now,
                "runner_status": "completed",
                "workload_status": finish_status,
                "measurement_recorded": True,
                "finished_wall_time": wall_now,
                "terminal_event": terminal_event_name,
                "return_code": return_code,
                "terminal_failure_reason": terminal_failure_reason,
                "total_runtime_seconds": float(t_finish - t_launch),
                "time_from_window_ready_to_finish_seconds": float(t_finish - t_window_ready),
            }
        )

        print("measurement recorded")
        print(f"task_id={task_obj.task_id}")
        print(f"gpu_uuid={gpu_uuid}")
        print(f"gpu_id={gpu_id}")
        print(f"launcher_pid={launcher_pid}")
        print(f"tracked_pid_after_window={tracked_pid_after_window}")
        print(f"finish_status={finish_status}")
        print(f"total_runtime_seconds={measurement['total_runtime_seconds']:.3f}")
        print(f"output_csv={args.output_csv}")
        print(f"index_csv={args.index_csv}")
        print(
            "risk_scores:",
            {
                "smact_risk": measurement.get("smact_risk", measurement.get("smact")),
                "smocc_risk": measurement.get("smocc_risk", measurement.get("smocc")),
                "drama_risk": measurement.get("drama_risk", measurement.get("drama")),
            },
        )

        _ = monitor_thread
        return 0

    except Exception as exc:
        wall_now = dt.datetime.now().isoformat()
        failure_reason = f"{type(exc).__name__}: {exc}"

        if t_launch is not None:
            index_row["total_runtime_seconds"] = float(time.monotonic() - t_launch)
        else:
            index_row["total_runtime_seconds"] = float(time.monotonic() - t_start)

        index_row.update(
            {
                "recorded_at": wall_now,
                "runner_status": "error",
                "workload_status": finish_status,
                "failure_stage": stage,
                "failure_reason": failure_reason,
                "measurement_recorded": measurement_recorded,
                "finished_wall_time": wall_now,
                "event_path": event_path,
                "out_log": out_log,
                "err_log": err_log,
                "time_log": time_log,
                "gpu_uuid": gpu_uuid,
                "gpu_id": gpu_id,
                "launcher_pid": None if launcher_pid is None else int(launcher_pid),
                "tracked_pid_after_ttfk": None if tracked_pid_after_ttfk is None else int(tracked_pid_after_ttfk),
                "tracked_pid_after_window": None if tracked_pid_after_window is None else int(tracked_pid_after_window),
                "terminal_event": terminal_event_name,
                "return_code": return_code,
                "terminal_failure_reason": terminal_failure_reason,
            }
        )

        if event_path is not None:
            append_jsonl_event(
                event_path=event_path,
                record={
                    "event": "threshold_runner_error",
                    "timestamp": wall_now,
                    "task_id": None if task_obj is None else str(task_obj.task_id),
                    "task": task_path,
                    "workdir": workdir,
                    "gpu_uuid": gpu_uuid,
                    "gpu_id": gpu_id,
                    "launcher_pid": launcher_pid,
                    "run_id": run_id,
                    "failure_stage": stage,
                    "failure_reason": failure_reason,
                },
            )

        print(f"threshold runner failed at stage={stage}: {failure_reason}", file=sys.stderr)
        return 1

    finally:
        append_run_index_csv(args.index_csv, index_row)

if __name__ == "__main__":
    raise SystemExit(main())